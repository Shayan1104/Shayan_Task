import numpy as np

one_dimensional = np.array([1, 2, 3, 4])
two_dimensional = np.array([[1, 2, 3], [4, 5, 6]])
three_dimensional = np.array([[[1, 2], [3, 4]], [[5, 6], [7, 8]]])

print("One-dimensional shape:", one_dimensional.shape)
print("Two-dimensional shape:", two_dimensional.shape)
print("Three-dimensional shape:", three_dimensional.shape)
